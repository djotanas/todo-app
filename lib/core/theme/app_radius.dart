/// Theme constant for border radius values.
abstract class AppRadius {
  const AppRadius._();

  /// Small radius value (4px).
  static const double sm = 4;

  /// Medium radius value (8px).
  static const double md = 8;

  /// Large radius value (16px).
  static const double lg = 16;

  /// Extra large radius value (24px).
  static const double xl = 24;

  /// Full radius value for creating pill shapes (999px).
  static const double full = 999;
}
